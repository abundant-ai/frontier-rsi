"""Run public custom cases through the existing numerical and timing machinery."""
from __future__ import annotations

import argparse
import gc
import json
import sys
from pathlib import Path

import torch
from safetensors.torch import load_file, save_file

from graph_checks import compare
from kernel_ops import output_and_gradients, reference
from practice_cases import Case, read_cases
from practice_inputs import Values, make_inputs
from restricted import load
from sweep_protocol import read_contract


class InputSuite:
    """Adapt validated public specifications to the shared worker's input API."""

    def __init__(self, cases: list[Case]) -> None:
        """Retain shape metadata, without allocating or caching tensor values.

        Args:
            cases: Validated specifications in execution order.
        """
        self.cases = cases

    def __call__(self, kind: str, seed: int, index: int, device: str = "cpu",
                 smoke: bool = False) -> Values:
        """Generate one example for the worker or independent reference checker.

        Args:
            kind: Must identify causal attention.
            seed: Tensor-value seed supplied by the existing worker.
            index: Position in this suite.
            device: Torch device for allocation.
            smoke: Unsupported because custom shapes must remain unchanged.

        Returns:
            Fresh tensors matching the specified dimensions and seed.

        Raises:
            ValueError: The operation, index or smoke flag is invalid.
        """
        if kind != "op01" or smoke or not 0 <= index < len(self.cases):
            raise ValueError("Invalid custom attention case request")
        return make_inputs(self.cases[index], seed, device)


def reference_output(values: Values) -> torch.Tensor:
    """Evaluate causal attention using the public mathematical reference.

    Args:
        values: Q, K, V and a causal mask generated by the development tool.

    Returns:
        The attention output tensor, with its autograd history intact.
    """
    return reference("op01", values)


def correctness_outputs(candidate: Path, cases: list[Case], seed: int,
                        config: Path, out: Path) -> None:
    """Save untimed output and gradient tensors from the restricted submission.

    Args:
        candidate: Submitted Python file, loaded by the ordinary restricted API.
        cases: Public input specifications.
        seed: Sweep seed used for all cases.
        config: Numerical contract including the memory cap.
        out: Existing output directory for tensors and execution metadata.
    """
    contract = read_contract(config)
    torch.set_num_threads(1)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.cuda.set_per_process_memory_fraction(min(1., contract["memory_gib"] * 1024**3 /
                                                  torch.cuda.get_device_properties(0).total_memory))
    fn = load(candidate, ["run"]).run
    torch.cuda.reset_peak_memory_stats()
    for index, case in enumerate(cases):
        values = make_inputs(case, seed)
        outputs = output_and_gradients(fn, values, True)
        if len(outputs) != 4 or any(type(value) is not torch.Tensor or value.device.type != "cuda"
                                    for value in outputs):
            raise ValueError("Expected a CUDA output and Q, K, V gradients")
        save_file({f"output_{i}": value.cpu().contiguous().clone() for i, value in enumerate(outputs)},
                  str(out / f"case-{index}.safetensors"))
        del values, outputs
        gc.collect()
        torch.cuda.empty_cache()
        print(json.dumps({"event": "case_computed", "index": index}), flush=True)
    (out / "execution.json").write_text(json.dumps({
        "peak_allocated_bytes": torch.cuda.max_memory_allocated(),
        "memory_scope": "one_case_at_a_time", "timed": False}, indent=2))


def check_outputs(cases: list[Case], seed: int, config: Path, out: Path) -> None:
    """Independently check saved outputs with per-output numerical diagnostics.

    This process never imports the submission. The same comparator used by the
    sweep checker enforces output shape, dtype, finiteness and NRMSE tolerance.

    Args:
        cases: Input specifications saved before starting the candidate process.
        seed: Sweep seed used by the candidate worker.
        config: Numerical contract consumed by the shared comparator.
        out: Directory containing saved output and gradient tensors.
    """
    contract = read_contract(config)
    torch.set_num_threads(1)
    torch.backends.cuda.matmul.allow_tf32 = False
    results: list[dict[str, object]] = []
    failed = False
    for index, case in enumerate(cases):
        values = make_inputs(case, seed)
        expected = output_and_gradients(reference_output, values, True)
        saved = load_file(str(out / f"case-{index}.safetensors"), device="cuda")
        if set(saved) != {f"output_{i}" for i in range(4)}:
            raise ValueError("Expected exactly the attention output and Q, K, V gradients")
        actual = [saved[f"output_{i}"] for i in range(4)]
        result: dict[str, object] = {"index": index, "case": case, "passed": True}
        try:
            compare(actual, expected, contract, values)
        except ValueError as error:
            result.update(passed=False, error=str(error))
            failed = True
        errors: dict[str, float | None] = {}
        for name, value, target in zip(("output", "dq", "dk", "dv"), actual, expected, strict=True):
            error = None
            if value.shape == target.shape and bool(torch.isfinite(value).all()):
                error = float((value.double() - target.double()).norm() / target.double().norm().clamp_min(1e-8))
            errors[name] = error
        result["nrmse"] = errors
        results.append(result)
        del values, expected, actual, saved
        gc.collect()
        torch.cuda.empty_cache()
        print(json.dumps({"event": "case_checked", "index": index, "passed": result["passed"]}), flush=True)
    (out / "correctness.json").write_text(json.dumps({
        "correctness_passed": not failed, "cases": results}, indent=2, allow_nan=False))
    if failed:
        raise SystemExit(1)


def main() -> None:
    """Dispatch development phases while preserving the shared timing worker.

    Only the public input factory is replaced for timing. CUDA capture, warmup,
    refresh, events, GPU checks and replay measurement remain in sweep_worker.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("phase", choices=("measure", "outputs", "check"))
    parser.add_argument("--cases", type=Path, required=True)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--candidate", type=Path, default=Path("/app/submission/candidate.py"))
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    cases = read_cases(args.cases)
    if args.phase == "measure":
        import sweep_worker
        sweep_worker.inputs = InputSuite(cases)
        sys.argv = ["sweep_worker.py", "--candidate", str(args.candidate), "--config", str(args.config),
                    "--seed", str(args.seed), "--out", str(args.out)]
        sweep_worker.main()
    elif args.phase == "outputs":
        correctness_outputs(args.candidate, cases, args.seed, args.config, args.out)
    else:
        check_outputs(cases, args.seed, args.config, args.out)


if __name__ == "__main__":
    main()
